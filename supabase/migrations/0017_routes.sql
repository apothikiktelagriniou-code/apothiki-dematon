create table if not exists public.route_times (
  id uuid primary key default gen_random_uuid(),
  dest text not null, time text not null check (time ~ '^[0-2][0-9]:[0-5][0-9]$'),
  days text not null default '1111111' check (days ~ '^[01]{7}$'),
  express boolean not null default false, conn boolean not null default false,
  notes text, active boolean not null default true, source text default 'ktel-aitolnias.gr', updated_at timestamptz not null default now());
create unique index if not exists route_times_u on public.route_times (dest, time, days);
create table if not exists public.route_lines (
  name text primary key, stops text[] not null, ord int not null default 0);
alter table public.route_times enable row level security; alter table public.route_lines enable row level security;
drop policy if exists staff_all on public.route_times; create policy staff_all on public.route_times for all to authenticated using (true) with check (true);
drop policy if exists staff_all on public.route_lines; create policy staff_all on public.route_lines for all to authenticated using (true) with check (true);
